def main():
    bad = 0
    for title, desc, flags in DESC_FLAG_CASES:
        got = classify(title, desc)["flags"]
        if got != flags:
            bad += 1
            print(f"FAIL: {title!r} + desc {desc!r}: expected {flags}, got {got}")
    for title, desc, expected in DESC_CASES:
        got = classify(title, desc)["model"]
        if got != expected:
            bad += 1
            print(f"FAIL: {title!r} + desc {desc!r}: expected {expected}, got {got}")
    for title, flags, kit in FLAG_CASES:
        got = classify(title)
        if sorted(got["flags"]) != sorted(flags) or (kit and got["kit"] != kit):
            bad += 1
            print(f"FAIL: {title!r}: expected {flags} {kit}, got {got['flags']} {got['kit']}")
    for title, brand, expected in CASES:
        got = classify(title, vinted_brand=brand)["model"]
        if got != expected:
            bad += 1
            print(f"FAIL: {title!r}: expected {expected}, got {got}")
    for title, expected in JUNK_CASES:
        got = junk_reason(title)
        if got != expected:
            bad += 1
            print(f"FAIL: {title!r}: expected junk {expected}, got {got}")
    from tracker.models import camera_name, siblings
    for text, from_photo, expected in NAME_CASES:
        got = camera_name(text, from_photo=from_photo)
        if got != expected:
            bad += 1
            print(f"FAIL: name {text!r}: expected {expected}, got {got}")
    if siblings("Minolta", "X-300") != ["Minolta X-1", "Minolta X-700", "Minolta X-500"] or siblings("Canon", "AE-1"):
        bad += 1
        print("FAIL: siblings", siblings("Minolta", "X-300"), siblings("Canon", "AE-1"))
    from tracker.kinds import camera_kind
    for name, kind in (("Minolta X-300", "полуавтомат / электроника"), ("Minolta SRT100X", "механика"),
                       ("Nikon F-401X", "автофокус"), ("Konica C35", "мыльница"), ("Fujica STX-1N", "механика"),
                       ("Fujica Single-8", "кино"), ("Revue AC4", "?"), ("Zeiss Ikon Contaflex", "механика")):
        if camera_kind(name) != kind:
            bad += 1
            print(f"FAIL: kind {name}: expected {kind}, got {camera_kind(name)}")
    total = len(CASES) + len(FLAG_CASES) + len(DESC_CASES) + len(DESC_FLAG_CASES) + len(JUNK_CASES) + len(NAME_CASES) + 2
    print(f"{total - bad}/{total} passed")

if __name__ == "__main__":
    main()
