def main():
    bad = 0
    for title, desc, flags in DESC_FLAG_CASES:
        got = classify(title, desc)["flags"]
        if got != flags:
            bad += 1
            print(f"FAIL: {title!r} + desc {desc!r}: expected {flags}, got {got}")
    for title, desc, expected in DESC_CASES:
        got = classify(title, desc)["model"]
        if got != expected:
            bad += 1
            print(f"FAIL: {title!r} + desc {desc!r}: expected {expected}, got {got}")
    for title, flags, kit in FLAG_CASES:
        got = classify(title)
        if sorted(got["flags"]) != sorted(flags) or (kit and got["kit"] != kit):
            bad += 1
            print(f"FAIL: {title!r}: expected {flags} {kit}, got {got['flags']} {got['kit']}")
    for title, brand, expected in CASES:
        got = classify(title, vinted_brand=brand)["model"]
        if got != expected:
            bad += 1
            print(f"FAIL: {title!r}: expected {expected}, got {got}")
    total = len(CASES) + len(FLAG_CASES) + len(DESC_CASES) + len(DESC_FLAG_CASES)
    print(f"{total - bad}/{total} passed")

if __name__ == "__main__":
    main()
